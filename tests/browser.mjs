// Optional integration suite. See README for external browser-tool installation.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { readFile } from 'node:fs/promises';
const root = process.env.BROWSER_MODULE_ROOT || '/tmp/augusta-browser/node_modules';
const { chromium } = await import(pathToFileURL(`${root}/playwright/index.mjs`));
const { default: AxeBuilder } = await import(pathToFileURL(`${root}/@axe-core/playwright/dist/index.mjs`));
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
const base = process.env.SITE_URL || 'http://127.0.0.1:8000/Augusta-Recruiting/';
let checks = 0;
function check(ok, message) { assert.ok(ok, message); checks++; console.log(`PASS ${message}`); }
try {
  const context = await browser.newContext({ viewport: {width:1440,height:1100}, acceptDownloads:true });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base); await page.waitForSelector('#risk-rows tr');
  check(await page.locator('#risk-rows tr').count() === 5, 'all five risks load under repository subpath');
  check(JSON.stringify(await page.locator('.metric-value').allTextContents()) === JSON.stringify(['5','1','4','3', String((await page.evaluate(async () => {const r=await(await fetch('data/risks.json')).json();return r.filter(x=>x.nextReview<=new Date().toISOString().slice(0,10)&&x.status!=='Closed').length;})))]), 'dashboard matches data and UTC review date');
  check(await page.locator('.matrix-cell').count() === 25, '25 matrix cells');
  check(await page.locator('.matrix-cell[aria-label="Likelihood 4, impact 4, High"] .risk-marker').count() === 2, 'shared inherent cell contains both risks');
  await page.getByLabel('Search register', {exact:true}).fill('Candidate Data');
  check(await page.locator('#risk-rows tr').count() === 1,'search filters records');
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('#risk-rows tr').length===5);
  await page.getByLabel('Category',{exact:true}).selectOption('Fraud');
  await page.getByLabel('Inherent severity',{exact:true}).selectOption('High');
  await page.getByLabel('Workflow status',{exact:true}).selectOption('In treatment');
  check(await page.locator('#risk-rows th').textContent()==='R-003','combined category, severity and status filters');
  await page.getByLabel('Search register',{exact:true}).fill('no matching record');
  check(await page.locator('#empty-state').isVisible(),'empty result message');
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('#risk-rows tr').length===5);
  await page.locator('[data-sort="inherent"]').click();
  check(await page.locator('#risk-rows tr').first().locator('td.score-value').first().textContent()==='12','numeric ascending sort');
  await page.locator('[data-sort="inherent"]').click();
  check(await page.locator('#risk-rows tr').first().locator('th').textContent()==='R-001','numeric descending sort');
  const marker = page.locator('.matrix-cell').getByRole('button',{name:'R-001: Candidate Data Exposure, open details'});
  await marker.click();
  check(await page.getByRole('dialog').isVisible(),'matrix opens detail dialog');
  for (const text of ['Causes','Potential consequences','Existing hypothetical controls','Planned treatment actions','Assessment & change history','Proposed residual target']) check((await page.locator('#risk-detail').innerText()).includes(text),`detail includes ${text}`);
  check(await page.evaluate(()=>document.activeElement.id)==='close-dialog','dialog initial focus');
  await page.keyboard.press('Shift+Tab');
  check(await page.evaluate(()=>document.querySelector('dialog').contains(document.activeElement)),'modal keyboard focus containment');
  await page.keyboard.press('Escape');
  check(await marker.evaluate(el=>el===document.activeElement),'Escape closes and restores focus');
  await page.getByText('Proposed residual',{exact:true}).click();
  check(await page.locator('.matrix-cell[aria-label="Likelihood 2, impact 3, Moderate"] .risk-marker').count()===3,'target matrix positions and multiple risks');
  await page.getByText('Read the matrix as a list',{exact:true}).click();
  check((await page.locator('#matrix-list').innerText()).includes('proposed target'),'accessible matrix alternative identifies targets');
  await page.locator('#risk-rows').getByRole('button',{name:'R-001: Candidate Data Exposure, open details'}).click();
  check(await page.getByRole('dialog').isVisible(),'table opens detail dialog');
  const detailAudit=await new AxeBuilder({page}).analyze();
  check(detailAudit.violations.length===0,`dialog accessibility (${detailAudit.violations.map(v=>v.id).join(', ')})`);
  await page.getByRole('button',{name:'Close risk details'}).click();
  const downloadWait=page.waitForEvent('download'); await page.locator('#export').click();const download=await downloadWait;
  const csv=await readFile(await download.path(),'utf8');
  check(csv.includes('R-005')&&csv.includes('"20","Critical"')&&csv.includes('Proposed residual score'),'downloaded CSV contains full calculated register');
  const audit=await new AxeBuilder({page}).analyze();
  check(audit.violations.length===0,`desktop accessibility (${audit.violations.map(v=>`${v.id}: ${v.nodes.map(n=>n.target).join(';')}`).join(', ')})`);
  await page.screenshot({path:'/tmp/augusta-desktop.png',fullPage:true});
  for (const width of [768,390,320]) {
    await page.setViewportSize({width,height:900});
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`no page overflow at ${width}px`);
  }
  const mobileAudit=await new AxeBuilder({page}).analyze();
  check(mobileAudit.violations.length===0,`mobile accessibility (${mobileAudit.violations.map(v=>v.id).join(', ')})`);
  await page.setViewportSize({width:390,height:900});await page.screenshot({path:'/tmp/augusta-mobile.png',fullPage:true});
  check(errors.length===0,`no JavaScript errors (${errors.join(', ')})`);
  await page.route('**/data/risks.json',route=>route.fulfill({status:503,body:'Unavailable'}));await page.reload();
  await page.getByRole('alert').waitFor();
  check((await page.getByRole('alert').innerText()).includes('could not be loaded'),'HTTP data error shown gracefully');
  check(await page.locator('#export').isDisabled(),'export disabled on data failure');
  await page.unroute('**/data/risks.json');
  await page.route('**/data/risks.json',route=>route.fulfill({status:200,contentType:'application/json',body:'[{"id":"bad"}]'}));await page.reload();await page.getByRole('alert').waitFor();
  check((await page.getByRole('alert').innerText()).includes('could not be loaded'),'invalid JSON records rejected gracefully');
  await page.unroute('**/data/risks.json');
  await page.route('**/data/risks.json',async route=>{const response=await route.fetch();const data=await response.json();data[0].title='<img src=x onerror=alert(1)>';await route.fulfill({json:data});});
  await page.reload();await page.waitForSelector('#risk-rows tr');
  check(await page.locator('#risk-rows img').count()===0&&(await page.locator('#risk-rows').innerText()).includes('<img src=x'),'risk text rendered without HTML injection');
  const noJS=await browser.newContext({javaScriptEnabled:false});const staticPage=await noJS.newPage();await staticPage.goto(base);
  check(await staticPage.locator('noscript').isVisible(),'JavaScript-disabled fallback');await noJS.close();
  console.log(`Browser checks: ${checks} passed.`);
} finally { await browser.close(); }
